import PDFDocument from 'pdfkit';

export function generateEvaluationReportPdf({ report, interview, candidate }) {
  return new Promise((resolve, reject) => {
    const document = new PDFDocument({ size: 'A4', margin: 44, info: { Title: `Interview evaluation - ${interview.role}`, Author: 'InterviewAI' } });
    const chunks = [];
    document.on('data', (chunk) => chunks.push(chunk));
    document.on('end', () => resolve(Buffer.concat(chunks)));
    document.on('error', reject);

    const heading = (text) => {
      ensureSpace(document, 32);
      document.fillColor('#1e293b').font('Helvetica-Bold').fontSize(14).text(text);
      document.moveDown(0.45);
    };
    const list = (items, empty) => {
      if (!items?.length) document.fillColor('#475569').font('Helvetica-Oblique').fontSize(10).text(empty);
      else items.forEach((item) => {
        ensureSpace(document, 24);
        document.fillColor('#334155').font('Helvetica').fontSize(10).text(`• ${item}`, { indent: 10, paragraphGap: 5 });
      });
      document.moveDown(0.4);
    };

    document.fillColor('#4f46e5').font('Helvetica-Bold').fontSize(23).text('Interview Evaluation Report');
    document.fillColor('#475569').font('Helvetica').fontSize(10).text('Generated by InterviewAI');
    document.moveDown();
    document.fillColor('#0f172a').font('Helvetica-Bold').fontSize(16).text(candidate?.name || 'Candidate');
    document.fillColor('#475569').font('Helvetica').fontSize(10).text(`${interview.role} · ${titleCase(interview.interviewType)} · ${titleCase(interview.difficulty)}`);
    document.text(`Interview date: ${formatDate(interview.endedAt || interview.createdAt)}`);
    document.text(`Report date: ${formatDate(report.createdAt)}`);
    document.moveDown();

    document.roundedRect(44, document.y, 507, 62, 8).fill('#eef2ff');
    document.fillColor('#3730a3').font('Helvetica-Bold').fontSize(11).text('OVERALL SCORE', 60, document.y - 49);
    document.fontSize(30).text(`${report.overallScore}/100`, 60, document.y + 2);
    document.moveDown(2.5);

    heading('Score breakdown');
    const scores = [['Technical', report.technicalScore], ['Communication', report.communicationScore], ['Problem solving', report.problemSolvingScore], ['Confidence', report.confidenceScore], ['Answer quality', report.answerQualityScore]];
    scores.forEach(([label, score]) => {
      ensureSpace(document, 18);
      document.fillColor('#334155').font('Helvetica').fontSize(10).text(`${label}: `, { continued: true }).font('Helvetica-Bold').text(`${score ?? 0}/100`);
    });
    document.moveDown();

    heading('Strengths');
    list(report.strengths, 'No demonstrated strengths were identified from the submitted responses.');
    heading('Areas to improve');
    list(report.weaknesses, 'No improvement areas were recorded.');
    heading('Recommended next steps');
    list(report.suggestions, 'No next steps were recorded.');

    heading('Video monitoring');
    const warnings = report.proctoringWarnings || [];
    document.fillColor('#334155').font('Helvetica').fontSize(10).text(`Warnings recorded: ${report.proctoringWarningCount || 0}. Score adjustment: ${report.proctoringScoreAdjustment || 0}.`);
    if (warnings.length) list(warnings.map((warning) => `${warning.message || warning.type} (Question ${(warning.questionIndex ?? 0) + 1})`), '');
    else document.moveDown(0.5);

    heading('Interview questions and responses');
    const answers = new Map((interview.answers || []).map((answer) => [Number(answer.questionIndex), answer]));
    (interview.questions || []).forEach((question, index) => {
      ensureSpace(document, 54);
      const answer = answers.get(index);
      document.fillColor('#1e293b').font('Helvetica-Bold').fontSize(10).text(`Question ${index + 1}: ${question.question}`);
      const response = answer?.status === 'skipped' ? 'Skipped by candidate.' : (answer?.transcript || answer?.answer || 'No response submitted.');
      document.fillColor('#475569').font('Helvetica').fontSize(10).text(`Response: ${response}`, { paragraphGap: 9 });
    });
    document.end();
  });
}

function ensureSpace(document, required) {
  if (document.y + required > document.page.height - document.page.margins.bottom) document.addPage();
}
function titleCase(value = '') { return String(value).replace(/-/g, ' ').replace(/\b\w/g, (letter) => letter.toUpperCase()); }
function formatDate(value) { return value ? new Intl.DateTimeFormat('en', { dateStyle: 'medium' }).format(new Date(value)) : 'Not available'; }
